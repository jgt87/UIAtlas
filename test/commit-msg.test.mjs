// Commit-message check: agent trailers are refused; ordinary messages and human co-authors pass.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { agentTrailers } from '../scripts/check-commit-msg.mjs';

test('agent co-author, session and "generated with" lines are found', () => {
  for (const line of ['Co-Authored-By: Claude Example <noreply@example.test>', 'co-authored-by: GitHub Copilot <x@example.test>',
    'Claude-Session: abc123', '🤖 Generated with [Claude Code](https://example.test)', 'Generated by Codex'])
    assert.deepEqual(agentTrailers(`Fix the export\n\nBody text.\n\n${line}\n`), [line], line);
});

test('ordinary messages, human co-authors and git comment lines pass', () => {
  assert.deepEqual(agentTrailers('Viewer: wrap long names\n\nCo-Authored-By: Ada Example <ada@example.test>\n'), []);
  assert.deepEqual(agentTrailers('Import: read Codex-free templates\n\nMentions claude in prose, which is fine.\n'), []);
  assert.deepEqual(agentTrailers('Fix\n# Co-Authored-By: Claude <x@example.test>\n'), [], 'comment lines are not part of the message');
});

test('the CLI exits 1 on a trailer and 0 on a clean message', () => {
  const dir = mkdtempSync(path.join(os.tmpdir(), 'atlas-msg-')), script = path.resolve('scripts/check-commit-msg.mjs');
  const clean = path.join(dir, 'clean'), bad = path.join(dir, 'bad');
  writeFileSync(clean, 'Export: split the token sheet builder\n'); writeFileSync(bad, 'Export\n\nCo-Authored-By: Claude <x@example.test>\n');
  execFileSync(process.execPath, [script, clean], { stdio: 'pipe' });
  assert.throws(() => execFileSync(process.execPath, [script, bad], { stdio: 'pipe' }), e => e.status === 1);
});
